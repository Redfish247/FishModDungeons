import re,os,sys
src='dungeons-26.1.2/src/main'
C=["WHITE","ORANGE","MAGENTA","LIGHT_BLUE","YELLOW","LIME","PINK","GRAY","LIGHT_GRAY","CYAN","PURPLE","BLUE","BROWN","GREEN","RED","BLACK"]
acc=lambda c:(lambda p:p[0].lower()+''.join(x.capitalize() for x in p[1:]))(c.split('_'))
CA="|".join(sorted(C,key=len,reverse=True))
kinds={'Blocks':{'WOOL':'WOOL','TERRACOTTA':'DYED_TERRACOTTA','STAINED_GLASS_PANE':'STAINED_GLASS_PANE','STAINED_GLASS':'STAINED_GLASS','CARPET':'CARPET'},
       'Items':{'WOOL':'WOOL','TERRACOTTA':'DYED_TERRACOTTA','STAINED_GLASS_PANE':'STAINED_GLASS_PANE','DYE':'DYE'}}
pat=re.compile(r'(?<![\w.])((?:net\.minecraft\.world\.(?:item\.Items|level\.block\.Blocks))|Blocks|Items)\.(%s)_(WOOL|TERRACOTTA|STAINED_GLASS_PANE|STAINED_GLASS|DYE|CARPET)\b'%CA)
used={'Blocks':set(),'Items':set()}
for root,_,fs in os.walk(src+'/kotlin'):
    for f in fs:
        if not f.endswith(('.kt','.java')) or f.startswith('ColorCompat'): continue
        p=os.path.join(root,f); t=open(p,encoding='utf8').read()
        def r(m):
            base=m.group(1).split('.')[-1]; k=base
            if m.group(3) not in kinds[k]: return m.group(0)
            used[k].add((m.group(2),m.group(3)))
            return ('CB.' if k=='Blocks' else 'CI.')+m.group(2)+'_'+m.group(3)
        if f.endswith('.kt'):
            n=pat.sub(r,t)
            if n!=t:
                if 'import fishmod.compat.CB' not in n and 'fishmod.compat' not in t:
                    n=re.sub(r'^(package [^\n]*\n)',r'\1\nimport fishmod.compat.CB\nimport fishmod.compat.CI\n',n,count=1,flags=re.M)
                open(p,'w',encoding='utf8',newline='').write(n)
        else:
            if pat.search(t): print('JAVA uses',p)
used['Items'].update([('GRAY','DYE'),('LIME','DYE'),('LIGHT_GRAY','DYE')])
import re as _re
for root,_,fs in os.walk(src):
    for f in fs:
        if f.startswith('ColorCompat') or not f.endswith(('.kt','.java')): continue
        t=open(os.path.join(root,f),encoding='utf8').read()
        for m in _re.finditer(r'\b(CB|CI)\.(%s)_(WOOL|TERRACOTTA|STAINED_GLASS_PANE|STAINED_GLASS|DYE|CARPET)\b'%CA,t):
            used['Blocks' if m.group(1)=='CB' else 'Items'].add((m.group(2),m.group(3)))
def gen(v26):
    out=['package fishmod.compat','','// Generated by tools/gen-color-compat.py: colour blocks/items differ between 26.1 and 26.2.','import net.minecraft.world.item.Item','import net.minecraft.world.item.Items','import net.minecraft.world.level.block.Block','import net.minecraft.world.level.block.Blocks','']
    for k,name,t,hold in (('Blocks','CB','Block','Blocks'),('Items','CI','Item','Items')):
        out.append('object %s {'%name)
        for c,kind in sorted(used[k]):
            if v26: e='%s.%s_%s'%(hold,c,kind)
            else: e='%s.%s.%s()'%(hold,kinds[k][kind],acc(c))
            out.append('    @JvmField val %s_%s: %s = %s'%(c,kind,t,e))
        out.append('}')
    return '\n'.join(out)+'\n'
open('dungeons-26.1.2/src/main/kotlin/fishmod/compat/ColorCompat.kt','w').write(gen(True))
open('dungeons-26.2/src/main/kotlin/fishmod/compat/ColorCompat.kt','w').write(gen(False))
print({k:len(v) for k,v in used.items()})
